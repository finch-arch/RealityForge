#!/usr/bin/env python3
"""Describe an environment in words, get a walkable MuJoCo scene.

    ./venv/bin/python scene_describe.py "a temple courtyard with stone pillars"
    ./venv/bin/python scene_describe.py "a rooftop with chimneys" --save rooftop

Generation goes through the `claude` CLI, so it uses your existing Claude Code
auth — no separate API key. The generated geometry is then **validated and
repaired** against the policy's limits and **walk-tested** before being accepted;
that check is the point of this script, not the generation.

Accepted scenes are appended to `custom_presets.py`, which `scene_builder` picks
up, so `drive_g1.py --preset <name>` can teleoperate in them.
"""

import argparse
import json
import pathlib
import re
import subprocess
import sys

import scene_validate as sv

ROOT = pathlib.Path(__file__).parent
CUSTOM = ROOT / "custom_presets.py"

INSTRUCTIONS = """\
You are generating MuJoCo MJCF geometry for a humanoid robot walking simulation.

Output ONLY `<geom .../>` lines. No <worldbody>, no explanation, no markdown fences.

HARD CONSTRAINTS — the robot's controller is terrain-blind and a 6 cm step makes
it fall over, so these are not stylistic:
1. Every geom must be AT LEAST 0.40 m tall measured from the ground (for a box,
   pos z == size z >= 0.40; for a cylinder, pos z == size[1] >= 0.40). Never emit
   steps, kerbs, ramps or platforms the robot might walk onto.
2. Leave a clear corridor at least 1.8 m wide running along the +x axis from
   x=0 to x=20. Nothing may sit within 0.9 m of the y=0 centreline.
3. Nothing within 1.0 m of the origin — that is the spawn point.
4. The ground is a flat infinite plane already; do NOT emit a floor.

STYLE:
- Use only type="box", type="cylinder" or type="sphere".
- Use material="wood" or material="stone" (those are the only two defined).
- Give every geom a unique name.
- 15-40 geoms. Place things to both sides of the corridor to frame it.
- For a box, pos is the centre and size is HALF-extents, so a 4 m tall wall is
  pos="8 3 2.0" size="6 0.15 2.0".

Also output, as the LAST line only, a single line starting with `PROMPT:` giving a
one-sentence photorealistic description of this place, for a video model.

Environment to build: """


def generate(description: str, model_hint: str = "") -> tuple[str, str]:
    """Ask the claude CLI for geoms. Returns (geom_fragment, look_prompt)."""
    prompt = INSTRUCTIONS + description
    if model_hint:
        prompt += f"\n\nExtra guidance: {model_hint}"
    proc = subprocess.run(
        ["claude", "-p", prompt],
        capture_output=True, text=True, timeout=300, stdin=subprocess.DEVNULL)
    if proc.returncode != 0:
        sys.exit(f"claude CLI failed:\n{proc.stderr[:500]}")
    text = proc.stdout

    look = ""
    m = re.search(r"^PROMPT:\s*(.+)$", text, re.M)
    if m:
        look = m.group(1).strip()
        text = text[:m.start()]
    # Keep only geom lines, in case the model wrapped them in anything.
    geoms = "\n".join("    " + g.group(0)
                      for g in re.finditer(r"<geom\s+[^>]*?/>", text, re.S))
    return geoms + "\n", look


def walk_test(preset_name: str) -> bool:
    """Render a short clip headlessly; the script reports WALKED or FELL."""
    proc = subprocess.run(
        ["./venv/bin/python", "render_scene.py", "--preset", preset_name,
         "--seconds", "9", "--width", "640", "--height", "368",
         "--out", str(ROOT / "out" / f"_walktest_{preset_name}.mp4")],
        capture_output=True, text=True, timeout=600, cwd=ROOT)
    out = proc.stdout + proc.stderr
    for line in out.splitlines():
        if "walked to" in line or "VERDICT" in line:
            print("   ", line.strip())
    return "VERDICT: WALKED" in out


def save_preset(name: str, geoms: str, look: str) -> None:
    """Append to custom_presets.py, which scene_builder imports if present."""
    entry = {
        "geoms": geoms,
        "look": dict(base_rgb=(108, 104, 98), dirt_rgb=(84, 80, 76),
                     contrast=0.7, sky=("0.36 0.50 0.72", "0.84 0.88 0.92"),
                     repeat="1.5 1.5",
                     prompt=look or f"A photorealistic view of {name}."),
    }
    data = {}
    if CUSTOM.exists():
        text = CUSTOM.read_text()
        m = re.search(r"CUSTOM = (\{.*\})\s*$", text, re.S)
        if m:
            data = json.loads(m.group(1))
    data[name] = entry
    CUSTOM.write_text(
        '"""Scenes generated by scene_describe.py. Auto-appended; safe to edit."""\n'
        "import json\n\n"
        f"CUSTOM = {json.dumps(data, indent=2)}\n")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("description", help="the environment, in plain words")
    ap.add_argument("--save", default=None,
                    help="preset name to save as (default: derived from the text)")
    ap.add_argument("--retries", type=int, default=2,
                    help="regeneration attempts if validation fails")
    ap.add_argument("--no-walk-test", action="store_true")
    args = ap.parse_args()

    name = args.save or re.sub(r"[^a-z0-9]+", "_",
                               args.description.lower())[:24].strip("_")

    hint = ""
    for attempt in range(1, args.retries + 2):
        print(f"\n[{attempt}] generating geometry for: {args.description}")
        geoms, look = generate(args.description, hint)
        n = len(sv.parse_geoms(geoms))
        print(f"    {n} geoms returned")
        if not n:
            hint = "You returned no <geom/> lines. Output only geom elements."
            continue

        fixed, errors, fixes = sv.validate(geoms)
        for f in fixes:
            print(f"    repaired: {f}")
        if errors:
            for e in errors:
                print(f"    REJECTED: {e}")
            hint = ("Your previous attempt was rejected for: "
                    + "; ".join(errors) + ". Fix these specifically.")
            continue

        print(f"    validation PASSED ({len(fixes)} auto-repairs)")
        save_preset(name, fixed, look)
        print(f"    saved preset '{name}'")

        if args.no_walk_test:
            break
        print("    walk-testing ...")
        if walk_test(name):
            print(f"\nOK — teleoperate with:\n"
                  f"  ./venv/bin/python drive_g1.py --preset {name} --no-world\n")
            if look:
                print(f"matching LingBot prompt:\n  {look}\n")
            return
        hint = ("The robot fell over in your previous scene. Make the corridor "
                "wider and keep all geometry further from the centreline.")
        print("    walk test FAILED, regenerating")

    sys.exit("could not produce a walkable scene; try rephrasing the description")


if __name__ == "__main__":
    main()
